#!/usr/bin/env node
// Inlines every JPG the game loads as data URIs in assets/bundle.js, so index.html also
// works when opened straight from disk (file://). Run after the sprite and photo builds.
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scope = { window: {} };
for (const file of ['assets/sprites/manifest.js', 'assets/photos/credits.js', 'assets/voice/manifest.js']) {
  vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), scope);
}
// URLs in the manifests carry a ?v= content stamp; on disk the files are plain.
const plain = (src) => src.split('?')[0];
const files = [
  ...Object.values(scope.window.SPRITE_ATLAS.sheets).map((sheet) => plain(sheet.src)),
  ...scope.window.PHOTO_CREDITS.map((photo) => plain(photo.src || `assets/photos/${photo.name}.jpg`)),
];
const voices = Object.values(scope.window.VOICE_CLIPS || {}).map((clip) => plain(clip.src));
const mime = (file) => (file.endsWith('.m4a') ? 'audio/mp4' : file.endsWith('.mp3') ? 'audio/mpeg' : 'image/jpeg');
const data = Object.fromEntries(
  [...files, ...voices].map((file) => [file, `data:${mime(file)};base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`]),
);
// A browser told "immutable, one year" keeps a manifest until that year is up - so a bad
// cache cannot be fixed by headers alone. index.html always revalidates, so stamping the
// generated-manifest script tags there is what actually forces a poisoned cache to refetch.
const indexFile = path.join(root, 'index.html');
let html = fs.readFileSync(indexFile, 'utf8');
for (const manifest of ['assets/sprites/manifest.js', 'assets/photos/credits.js', 'assets/voice/manifest.js']) {
  const stamp = crypto.createHash('sha1').update(fs.readFileSync(path.join(root, manifest))).digest('hex').slice(0, 8);
  const pattern = new RegExp(`(<script src="${manifest.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')})(\\?v=[0-9a-f]+)?(">)`);
  if (!pattern.test(html)) throw new Error(`index.html does not load ${manifest}`);
  html = html.replace(pattern, `$1?v=${stamp}$3`);
}
fs.writeFileSync(indexFile, html);
console.log('stamped the manifest script tags in index.html');

const out = path.join(root, 'assets/bundle.js');
fs.writeFileSync(out, `// Generated by tools/bundle-assets.mjs - lets index.html run from file://.\nwindow.ASSET_DATA = ${JSON.stringify(data)};\n`);
console.log(`wrote assets/bundle.js (${files.length} JPGs, ${voices.length} voice clips, ${Math.round(fs.statSync(out).size / 1024)}KB)`);
